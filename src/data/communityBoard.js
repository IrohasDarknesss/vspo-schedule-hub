const STORAGE_KEY_COMMUNITY = 'vspo_community_threads_v2';

export function getStoredCommunityThreads() {
  if (typeof window === 'undefined') return INITIAL_THREADS;
  try {
    const raw = localStorage.getItem(STORAGE_KEY_COMMUNITY);
    if (!raw) return INITIAL_THREADS;
    const parsed = JSON.parse(raw);
    return parsed && parsed.length > 0 ? parsed : INITIAL_THREADS;
  } catch {
    return INITIAL_THREADS;
  }
}

export function saveCommunityThreads(threads) {
  if (typeof window === 'undefined') return;
  try {
    localStorage.setItem(STORAGE_KEY_COMMUNITY, JSON.stringify(threads));
  } catch (e) {
    console.error('Failed to save community threads', e);
  }
}
